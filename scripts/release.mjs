import {createHash} from 'node:crypto';
import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../dist/',import.meta.url),swURL=new URL('sw.js',root);
let sw=await readFile(swURL,'utf8');
const photoURL=new URL('photo.mjs',root);let photo=await readFile(photoURL,'utf8');
const photoHash=createHash('sha256');
for(const name of ['photo-worker.mjs','food-utils.mjs','models/food-clip-q8.onnx','models/food-labels.json','vendor/ort/ort.wasm.min.mjs','vendor/ort/ort-wasm-simd-threaded.mjs','vendor/ort/ort-wasm-simd-threaded.wasm'])photoHash.update(name).update(await readFile(new URL(name,root)));
photo=photo.replace(/const PHOTO_CACHE='[^']+';/,`const PHOTO_CACHE='bodytrack-photo-${photoHash.digest('hex').slice(0,12)}';`);await writeFile(photoURL,photo);
const names=['index.html','styles.css','app.mjs','core.mjs','store.mjs','food-utils.mjs','foods.json','photo.mjs','photo-worker.mjs','manifest.webmanifest','icons/icon.svg','icons/icon-192.png','icons/icon-512.png','icons/apple-touch-icon.png'];
const hash=createHash('sha256');
for(const name of names)hash.update(name).update(await readFile(new URL(name,root)));
hash.update(sw.replace(/const CACHE='[^']+';/,"const CACHE='bodytrack-shell-RELEASE';"));
const version=hash.digest('hex').slice(0,12);
sw=sw.replace(/const CACHE='[^']+';/,`const CACHE='bodytrack-shell-${version}';`);
await writeFile(swURL,sw);
console.log(`Offline shell release: ${version}`);
